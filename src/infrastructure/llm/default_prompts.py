"""Дефолтные системные промпты для режимов и судьи стадий.

Mode/quiz/stage_director промпты используют фактологию и образцовые диалоги
из content/cases/<case_id>/. Здесь мы только подставляем их в шаблоны.
"""

from __future__ import annotations

from typing import Final

from domain.states import Mode
from infrastructure.content.case_loader import load_case


def _facts() -> str:
    return load_case("cc_novichok").facts or "(фактология не загружена)"


def _dialogues() -> str:
    return load_case("cc_novichok").dialogues or "(образцовые диалоги не загружены)"



"""Состояния конечного автомата (FSM) обучающего тренажёра.

Каждое значение перечисления соответствует одному узлу FSM-диаграммы.
Порядок объявления отражает типичный путь сотрудника через тренажёр —
от инициализации до финала.

Группы состояний (соответствуют цветовым блокам диаграммы):

* **Инфраструктурные** — INIT, MENU, RESUME_PROMPT, WELCOME
* **Блок TRAINING** — TRAINING, TRAINING_QUIZ, TRAINING_EXPLAIN, TRAINING_DONE
* **Блок PRACTICE CYCLE** — EXAMPLE, EXAMPLE_DONE, PRACTICE, PRACTICE_EVAL,
  PRACTICE_PARTIAL, PRACTICE_SUCCESS, KNOWLEDGE, KNOWLEDGE_DONE
* **Предупреждения** — SKIP_WARNING_1, SKIP_WARNING_2
* **Финал** — FINISH
"""

from __future__ import annotations

from enum import StrEnum


class FSMState(StrEnum):
    """Полный список состояний FSM.

    Используется ``StrEnum``, чтобы значения сериализовались в строки
    без дополнительных преобразований (удобно для JSON / БД).

    Examples:
        >>> FSMState.INIT
        <FSMState.INIT: 'INIT'>
        >>> str(FSMState.TRAINING)
        'TRAINING'
        >>> FSMState("MENU") is FSMState.MENU
        True
    """

    # ------------------------------------------------------------------
    # Инфраструктурные состояния
    # ------------------------------------------------------------------

    INIT = "INIT"
    """Точка входа. Проверяется наличие и возраст существующей сессии."""

    RESUME_PROMPT = "RESUME_PROMPT"
    """Предложение продолжить прерванную сессию (< 48 ч) или начать заново."""

    MENU = "MENU"
    """Главное меню: выбор продукта, имя сотрудника, кнопка «Начать обучение»."""

    WELCOME = "WELCOME"
    """Стартовое приветственное сообщение с выбором режима обучения."""

    # ------------------------------------------------------------------
    # Блок TRAINING
    # ------------------------------------------------------------------

    TRAINING = "TRAINING"
    """Аватар рассказывает теорию по продукту (фактология)."""

    TRAINING_QUIZ = "TRAINING_QUIZ"
    """Проверочные вопросы по итогам теории (3 вопроса из чек-листа)."""

    TRAINING_EXPLAIN = "TRAINING_EXPLAIN"
    """Разбор неверного ответа: объяснение + повтор вопроса."""

    TRAINING_DONE = "TRAINING_DONE"
    """Завершение блока TRAINING. Переход к EXAMPLE."""

    # ------------------------------------------------------------------
    # Предупреждения при пропуске режимов
    # ------------------------------------------------------------------

    SKIP_WARNING_1 = "SKIP_WARNING_1"
    """Предупреждение при переходе к «Примеру» без прохождения «Обучения»."""

    SKIP_WARNING_2 = "SKIP_WARNING_2"
    """Предупреждение при переходе к «Практике» без прохождения «Обучения»."""

    # ------------------------------------------------------------------
    # Блок PRACTICE CYCLE
    # ------------------------------------------------------------------

    EXAMPLE = "EXAMPLE"
    """Аватар играет роль сотрудника банка, сотрудник — роль клиента."""

    EXAMPLE_DONE = "EXAMPLE_DONE"
    """Сценарий «Пример» завершён. Переход к PRACTICE."""

    PRACTICE = "PRACTICE"
    """Аватар играет роль клиента, сотрудник — роль сотрудника банка."""

    PRACTICE_EVAL = "PRACTICE_EVAL"
    """Оценка диалога «Практика» по чек-листу западающих зон."""

    PRACTICE_PARTIAL = "PRACTICE_PARTIAL"
    """Часть зон не отработана. Финальное сообщение + переход к KNOWLEDGE."""

    PRACTICE_SUCCESS = "PRACTICE_SUCCESS"
    """Зоны отработаны корректно. Финальное сообщение, успех."""

    KNOWLEDGE = "KNOWLEDGE"
    """Проработка западающих зон, переданных из PRACTICE_PARTIAL."""

    KNOWLEDGE_DONE = "KNOWLEDGE_DONE"
    """Зоны отработаны. Предложение повторить цикл EXAMPLE → PRACTICE."""

    # ------------------------------------------------------------------
    # Финал
    # ------------------------------------------------------------------

    FINISH = "FINISH"
    """Финальное состояние. Обучение полностью завершено."""


class Mode(StrEnum):
    """Режимы обучения, отслеживаемые в ``SessionContext.completed_modes``.

    Использует ``StrEnum`` (а не смешанный ``class Mode(str, Enum)``),
    чтобы:

    * семантика совпадала с :class:`FSMState`;
    * mypy в строгом режиме корректно видел все значения;
    * сравнение с обычными строками работало без ``.value``.
    """

    TRAINING = "training"
    EXAMPLE = "example"
    PRACTICE = "practice"
    KNOWLEDGE = "knowledge"

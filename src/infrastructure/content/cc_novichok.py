"""Контент курса КК_Новичок.

В Срезе 2 фактология и образцовые диалоги перенесены в content/cases/cc_novichok/.
Здесь остаются:
- START_MESSAGE — приветствие в WELCOME (читается из facts.md, секция «## Welcome»).
- TRAINING_BLOCKS — узкие keyword-блоки для stub-чекера и stub-квиза
  (используются только когда LLM недоступен).
- EXAMPLE_DIALOGUE / PRACTICE_SCENARIO / KNOWLEDGE_BLOCKS — fallback-контент
  для StubAvatar.

Когда GigaChat подключён, аватар и квиз ходят за фактологией и диалогами
напрямую в case_loader.load_case(...).
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from domain.types import Zone
from infrastructure.content.case_loader import load_case


def _extract_welcome() -> str:
    facts = load_case("cc_novichok").facts
    if not facts:
        return _DEFAULT_WELCOME
    # Берём блок между "## Welcome" и следующим "## ".
    m = re.search(r"##\s*Welcome\s*\n(.+?)(?:\n##\s|\Z)", facts, re.DOTALL | re.IGNORECASE)
    if not m:
        return _DEFAULT_WELCOME
    return m.group(1).strip() or _DEFAULT_WELCOME


_DEFAULT_WELCOME = (
    "Привет! Давай начнём обучение по продукту «Кредитная карта». "
    "Я расскажу теорию, покажу образцовый диалог и дам попрактиковаться."
)


START_MESSAGE: str = _extract_welcome()



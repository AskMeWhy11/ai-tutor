def default_mode_prompts(case_id: str = DEFAULT_CASE_ID) -> dict[Mode, str]:
    is_sales_technique = case_id != DEFAULT_CASE_ID
    training = _TRAINING_TEMPLATE_TECHNIQUE if is_sales_technique else _TRAINING_TEMPLATE
    example = _EXAMPLE_TEMPLATE_TECHNIQUE if is_sales_technique else _EXAMPLE_TEMPLATE
    return {
        Mode.TRAINING: training,
        Mode.EXAMPLE: example,
        Mode.PRACTICE: _PRACTICE_TEMPLATE,
        Mode.KNOWLEDGE: _KNOWLEDGE_TEMPLATE,
    }


def default_quiz_prompt(case_id: str = DEFAULT_CASE_ID) -> str:
    return _QUIZ_TEMPLATE_TECHNIQUE if case_id != DEFAULT_CASE_ID else _QUIZ_TEMPLATE


def default_stage_director_prompt(case_id: str = DEFAULT_CASE_ID) -> str:
    return _STAGE_DIRECTOR_TEMPLATE_TECHNIQUE if case_id != DEFAULT_CASE_ID else _STAGE_DIRECTOR_TEMPLATE
